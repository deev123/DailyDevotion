import { lazy, Suspense, useEffect, useState } from "react";
import Passage from "./Passage.tsx"
import NoteBox from "./NoteBox.tsx"
import VideoPlaylist from "./VideoPlaylist.tsx"
import LegacyPassage from "./LegacyPassage.tsx"
import Catechism from "./Catechism.tsx"
import Header from "./Header.tsx"
import Menu from "./Menu.tsx"
import { deletePdf } from "./pdfStorage.ts"

const PdfReader = lazy(() => import("./PdfReader.tsx"));

// Persisted type identifiers intentionally keep their original meanings:
// "passage" = LegacyPassage (Bible API), "passage2" = Passage (YouVersion).
// Do not rename these values: existing devices store them in componentsConfig.

type LegacyPassage_t = {
    type: "passage",
    id: string,
    list: string
}

type NoteBox_t = {
    type: "notebox",
    id: string
}

type VideoPlaylist_t = {
    type: "videoPlaylist",
    id: string,
    list: string
}

type Passage_t = {
    type: "passage2",
    id: string,
    list: string
}

type Catechism_t = {
    type: "catechism",
    id: string,
    list: string
}

type Component_t =
    | LegacyPassage_t
    | NoteBox_t
    | VideoPlaylist_t
    | Passage_t
    | Catechism_t
    | { type: "pdfReader"; id: string }

// New layouts start with YouVersion readers; saved layouts take precedence.
const componentsConfigDefault: Component_t[] = [
    {
        type: "passage2",
        id: "section1",
        list: "Psalms.txt",
    },
    {
        type: "passage2",
        id: "section2",
        list: "Bible_Chapters.txt",
    }
];

function Layout(){
    const [layoutError, setLayoutError] = useState("");
    
    let [componentsConfig, setComponentsConfig] = useState(loadComponentsConfig() || componentsConfigDefault); // loaded || default layout
     
    function loadComponentsConfig()
    {
        const json = localStorage.getItem("componentsConfig");

        // only basic check it has id and type since it is generated by the app anyway
        if(!json) return null;
        try{
            const config = JSON.parse(json);
            if (!Array.isArray(config)) return null;
            // skip if no id or no type
            return config.filter((component) => (component.id && component.type));
        } catch (e)
        {
            console.warn("Invalid stored config. Resorting to default...");
            return null;
        }
    }

    // load the layout from a json object
    function load()
    {    
        setComponentsConfig(() => {
            const config = loadComponentsConfig() || componentsConfigDefault;
            return config;
        });
    }

    function saveComponentsConfig(config: Component_t[])
    {
        localStorage.setItem("componentsConfig", JSON.stringify(config))
    }

    function moveUp(id: string)
    {
        setComponentsConfig( prev => {
            const index = prev.findIndex(c => c.id === id);
            if (index <= 0 || index === -1) return prev;

            // copy the list
            const newList = [...prev];
            // swap indexes
            let temp = newList[index -1];
            newList[index -1] = newList[index];
            newList[index] = temp;
            // save the config list
            saveComponentsConfig(newList);
            return newList;
        });
    }

    function moveDown(id: string)
    {
        setComponentsConfig( prev => {
            const index = prev.findIndex(c => c.id === id);
            if (index >= prev.length - 1 || index === -1) return prev;

            // copy the list
            const newList = [...prev];
            // swap indexes
            let temp = newList[index +1];
            newList[index +1] = newList[index];
            newList[index] = temp;
            // save the config list
            saveComponentsConfig(newList);
            return newList;
        });
    }

    async function deleteComponent(id: string)
    {
        setLayoutError("");
        if (componentsConfig.some((component: Component_t) => component.id === id && component.type === "pdfReader")) {
            try {
                // Keep the component available for retry if deleting its file fails.
                await deletePdf(id);
            } catch {
                setLayoutError("Could not delete the saved PDF. Please try deleting the component again.");
                return;
            }
        }
        setComponentsConfig((prev) => {
            const index = prev.findIndex(c => c.id === id);
            if(index === -1) return prev; // not found

            // Handle cleanup of local store values when deleted
            // Potentially better to make classes for each component with helpers like deleteStores()
            // but for now layout will manage cleanup here
            switch(prev[index].type){
                case "passage":
                    localStorage.removeItem(id + "_index");
                    break;
                case "notebox":
                    localStorage.removeItem(id + "_title");
                    localStorage.removeItem(id + "_text");
                    localStorage.removeItem(id + "_state");
                    break;
                case "videoPlaylist":
                    localStorage.removeItem(id + "_index");
                    break;
                case "passage2":
                    localStorage.removeItem(id + "_index");
                    localStorage.removeItem(id + "_version");
                    break;
                case "catechism":
                    localStorage.removeItem(id + "_index");
                    break;
            }

            // new list with the old index skipped
            const newList = [...prev.slice(0, index), ...prev.slice(index +1)];
            // save the new config list
            saveComponentsConfig(newList);
            return newList;
        });
    }

    // generate a unique id for a new component
    function generateId()
    {
        let id: string;
        do
        {
            id = "comp_" + Math.random().toString(36).slice(2, 9);
        } while (componentsConfig.some(c => c.id === id));
        return id;
    }

    function addComponent(config: Component_t)
    {
        setComponentsConfig( prev => {
            // add config onto the existing list and then save
            const newList = [...prev, config];
            // save the new config list
            saveComponentsConfig(newList);
            return newList;
        });
    }

    // load config from local storage when layout is first created
    useEffect(() => {
        load();
    }, []);

    // manually saving config instead of useeffect so that invalid loads wont save
    // but this means you do need to save config in the functions which modify it

    // addComponent takes a component_t config object as an argmunet to add to layout
    // these menu options define the configs to pass for each type of component
    let addElementOptions = [
    {
        label: "PDF reader",
        action: () => addComponent({ type: "pdfReader", id: generateId() })
    },
    {
        label: "Passage",
        action: () => {
            addComponent({
                type: "passage2",
                id: generateId(),
                list: "Bible_Chapters.txt"
            });
        }
    },
    {
        label: "Psalm",
        action: () => {
            addComponent({
                type: "passage2",
                id: generateId(),
                list: "Psalms.txt"
            });
        }
    },
    {
        label: "Note Box",
        action: () => {
            addComponent({
                type: "notebox",
                id: generateId(),
            });
        }
    },
    // video playlist
    {
        label: "Video Playlist",
        action: () => {
            addComponent({
                type: "videoPlaylist",
                id: generateId(),
                list: "NIV_Audio_Bible.json"
            });
        }
    },
    {
        label: "Legacy Passage",
        action: () => {
            addComponent({
                type: "passage",
                id: generateId(),
                list: "Bible_Chapters.txt"
            });
        }
    },
    {
        label: "Legacy Psalm",
        action: () => {
            addComponent({
                type: "passage",
                id: generateId(),
                list: "Psalms.txt"
            });
        }
    },
    {
        label: "Heidelberg Catechism",
        action: () => {
            addComponent({
                type: "catechism",
                id: generateId(),
                list: "Heidelberg_Catechism.json"
            });
        }
    }];

    // wraps the layout; the settings button is fixed-position so it floats over everything
    let elements = <>
        <Header/>
        <div className="container">
        {layoutError && <p className="passage-error" role="alert">{layoutError}</p>}
        {
            componentsConfig.map((c: Component_t) => {

            const layoutOptions = [
                {
                    label: "Move Up",
                    action: () => moveUp(c.id)
                },
                {
                    label: "Move Down",
                    action: () => moveDown(c.id)
                },
                {
                    label: "Delete",
                    action: () => deleteComponent(c.id)
                }
            ];

            // console.log(layoutControls);

            switch(c.type){
                case "pdfReader":
                    return <Suspense key={c.id} fallback={<section><p>Loading PDF reader…</p></section>}>
                        <PdfReader layoutOptions={layoutOptions} id={c.id}/>
                    </Suspense>;
                case "passage":
                    return <LegacyPassage layoutOptions={layoutOptions} id={c.id} list={c.list} key={c.id}/>;
                case "notebox":
                    return <NoteBox layoutOptions={layoutOptions} id={c.id} key={c.id}/>;
                case "videoPlaylist":
                    return <VideoPlaylist layoutOptions={layoutOptions} id={c.id} list={c.list} key={c.id}/>;
                case "passage2":
                    return <Passage layoutOptions={layoutOptions} id={c.id} list={c.list} key={c.id}/>;
                case "catechism":
                    return <Catechism layoutOptions={layoutOptions} id={c.id} list={c.list} key={c.id}/>;
                }
            })
        }
        <section className="add-component-container">
            <Menu options={addElementOptions}>
                <button className="add-component-button">+</button>
            </Menu>
        </section>
        </div>
    </>

    return elements
}

export default Layout
